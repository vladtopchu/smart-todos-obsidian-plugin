import { mkdir, copyFile, readFile, rm } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(await readFile(path.join(root, 'manifest.json'), 'utf8'));
if (manifest.id !== 'smart-todos' || manifest.name !== 'Smart Todo') throw new Error('Неверный ID или название личной сборки Smart Todo.');
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const versions = JSON.parse(await readFile(path.join(root, 'versions.json'), 'utf8'));
if (manifest.version !== pkg.version || versions[manifest.version] !== manifest.minAppVersion) throw new Error('Версии manifest.json, package.json и versions.json не согласованы.');
if (process.env.RELEASE_TAG && process.env.RELEASE_TAG !== manifest.version) throw new Error('Тег релиза должен совпадать с версией manifest.json (без префикса v).');
const destination = path.join(root, 'dist', manifest.id);
// Rebuild only this generated release folder; exclude local data.json and stale files.
await rm(destination, { recursive: true, force: true });
await mkdir(destination, { recursive: true });
const filenames = ['main.js', 'manifest.json', 'styles.css'];
for (const filename of filenames) await copyFile(path.join(root, filename), path.join(destination, filename));
const dist = path.join(root, 'dist');
const entries = filenames.map(name => `${manifest.id}/${name}`);
const hash = async filename => createHash('sha256').update(await readFile(path.join(dist, filename))).digest('hex');
const sums = await Promise.all(entries.map(async filename => `${await hash(filename)}  ${filename}`));
await writeFile(path.join(dist, 'SHA256SUMS'), `${sums.join('\n')}\n`);
const archive = `smart-todo-${manifest.version}.zip`;
await rm(path.join(root, 'dist', archive), { force: true });
execFileSync('zip', ['-q', '-X', archive, ...entries, 'SHA256SUMS'], { cwd: dist });
await writeFile(path.join(dist, `${archive}.sha256`), `${await hash(archive)}  ${archive}\n`);
console.log(`Готово: ${path.join(root, 'dist', archive)}`);
